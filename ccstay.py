def resolve_dir(query):
    path = os.path.abspath(os.path.expanduser(query))
    if os.path.isdir(path):
        return path
    hits, q = [], query.lower()
    for root, dirs, _ in os.walk(HOME):
        depth = root[len(HOME):].count(os.sep)
        dirs[:] = [] if depth >= 4 else [
            d for d in dirs if not d.startswith(".") and d != "node_modules" and (root, d) != (HOME, "Library")]
        hits += [os.path.join(root, d) for d in dirs if q in d.lower()]
    if len(hits) == 1:
        return hits[0]
    die(f"{len(hits)} folders match {query!r}:\n  " + "\n  ".join(sorted(hits)[:15]) if hits
        else f"no folder matches {query!r}")


def accept_trust(s):
    """Answer the folder trust prompt, which only appears for a folder never opened before."""
    pane = f"={s['name']}:"

    def screen():
        return in_tab(s, "return contents of s") if s["tty"] else tmux("capture-pane", "-p", "-t", pane).stdout

    def press(tmux_key, code):
        if s["tty"]:
            in_tab(s, f"tell s to write text {code} newline NO")
        else:
            tmux("send-keys", "-t", pane, tmux_key)

    if wait_for(lambda: "Yes, I trust this folder" in screen(), 8):
        press("Down", '((ASCII character 27) & "[B")')
        if wait_for(lambda: "❯ Yes, I trust" in screen(), 3):
            press("Enter", "(ASCII character 13)")


def cmd_new(a):
    cwd = resolve_dir(a.folder)
    live = sessions()
    folder = os.path.basename(cwd)
    if a.resume:
        if any(s["sid"] == a.resume for s in live):
            die("that conversation is already running")
    elif any(s["cwd"] == cwd for s in live):
        print(f"note: {folder} already has a running session")
    label = f"{folder}/{a.name}" if a.name else folder
    name = unique_name(label, {s["name"] for s in live})
    argv = resume_argv(a.resume, label) if a.resume else start_argv(label)
    term = "iterm" if a.no_tmux else pick_terminal(a.terminal)
    if a.no_tmux and (sys.platform != "darwin" or a.terminal not in (None, "iterm")):
        die("--no-tmux needs iTerm on macOS")
    if a.dry_run:
        print(f"{name}  {cwd}  ({term or 'detached'})\n{shlex.join(argv)}")
        return
    if a.no_tmux:
        tty = start_native(cwd, argv)
        match = {"tty": tty}
    else:
        term = start(name, cwd, argv, term)
        match = {"name": name}

    def started(require_meta=True):
        hit = next((x for x in sessions() if all(x[k] == v for k, v in match.items())), None)
        return hit if hit and (hit["meta"] or not require_meta) else None

    if a.trust:
        accept_trust({"tty": "", "name": name} if not a.no_tmux else {"tty": tty, "name": name})
    s = wait_for(started, 20)
    url = wait_for(lambda: url_of(meta(s["pid"])), 15 if REMOTE else 6) if s else ""  # may simply be off
    where = "in iterm, no tmux" if a.no_tmux else f"in {term}" if term else \
        f"detached, use: ccstay attach {shlex.quote(name)}"
    print(f"{name}  {where}")
    if url:
        print(url)
    elif not s:
        print(f"warning: claude has not registered yet, check: ccstay attach {shlex.quote(name)}")


def age(seconds):
    return f"{seconds / 86400:.0f}d" if seconds >= 86400 else f"{seconds / 3600:.0f}h" if seconds >= 3600 \
        else f"{seconds / 60:.0f}m"


def cmd_ls(a):
    keep = keep_ids()
    rows = sessions()
    for s in rows:
        state = "asleep" if s["asleep"] else s["status"] or "starting"
        idle = age(idle_seconds(s)) if s["meta"] else "-"
