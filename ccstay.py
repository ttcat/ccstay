def die(msg, code=1):
    print(f"ccstay: {msg}", file=sys.stderr)
    sys.exit(code)


def log(msg):
    with open(LOG, "a") as f:
        f.write(time.strftime("%Y-%m-%d %H:%M:%S ") + msg + "\n")


def clean_env():
    """Called from inside Claude Code, do not leak its variables into the sessions we start."""
    drop = ("TMUX", "TMUX_PANE", "ITERM_SESSION_ID", "TERM_SESSION_ID")  # a detached pane has no tab of its own
    env = {k: v for k, v in os.environ.items() if k not in drop}
    if "CLAUDECODE" in env:
        env = {k: v for k, v in env.items() if k != "CLAUDECODE" and not k.startswith("CLAUDE_CODE_")}
    return env


def tmux_base():
    exe = shutil.which("tmux") or die("tmux not found, install it first")
    return [exe, "-L", SOCKET, "-f", TMUX_CONF]


def tmux(*args):
    return subprocess.run(tmux_base() + list(args), capture_output=True, text=True, env=clean_env())


def claude_exe():
    return os.environ.get("CCSTAY_CLAUDE") or shutil.which("claude") or die("claude not found")


def write_atomic(path, text, keep_mode=False):
    tmp = f"{path}.{os.getpid()}"
    with open(os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600), "w", encoding="utf-8") as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    if keep_mode and os.path.exists(path):
        shutil.copymode(path, tmp)
    os.replace(tmp, path)


@contextmanager
def locked():
    """Ticks, hooks and commands all rewrite the same file."""
    with open(f"{STATE_DIR}/lock", "w") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        yield


def update_records(change):
    with locked():
        saved = read_snapshot()
        change(saved)
        write_atomic(SNAPSHOT, json.dumps(saved, ensure_ascii=False, indent=1))


def set_fields(session_id, **fields):
    def change(saved):
        saved[session_id] = {**saved.get(session_id, {}), **fields}
        saved[session_id].pop("missing_since", None)

    update_records(change)


def clean(text):
    """Titles reach tmux options, the terminal title and `ls`; control characters do not belong there."""
    return re.sub(r"[\x00-\x1f\x7f]+", " ", text or "")


def self_path():
    """A path that survives Python upgrades, for hooks and timers to call."""
    return shutil.which("ccstay") or os.path.realpath(__file__)


# Claude Code's own bookkeeping. ~/.claude/sessions/<pid>.json is internal.

def meta(pid):
    try:
        with open(f"{CLAUDE_DIR}/sessions/{pid}.json", encoding="utf-8") as f:
            m = json.load(f)
    except (OSError, ValueError):
        return None
    return m if m.get("sessionId") else None  # an unreadable record; doctor reports it


def transcript(cwd, sid):
    # claude counts JavaScript characters (an emoji is two) and cuts a long name, adding a hash we cannot recompute
    name = "".join(c if c.isascii() and c.isalnum() else "-" * (1 + (ord(c) > 0xFFFF)) for c in os.path.realpath(cwd))
    if len(name) > 200:
        return next(iter(glob.glob(f"{CLAUDE_DIR}/projects/{glob.escape(name[:200])}-*/{sid}.jsonl")), "")
    return f"{CLAUDE_DIR}/projects/{name}/{sid}.jsonl"


def moved_transcript(sid):
    """The transcript of a session whose folder moved stays under the old path, and claude -r still finds it."""
    return next(iter(glob.glob(f"{CLAUDE_DIR}/projects/*/{sid}.jsonl")), "")


def last_active(m):
    t = (m.get("statusUpdatedAt") or m.get("updatedAt") or 0) / 1000
    try:
        return max(t, os.path.getmtime(transcript(m.get("cwd", ""), m.get("sessionId", ""))))
    except OSError:
        return t


def url_of(m):
    return f"https://claude.ai/code/{m['bridgeSessionId']}" if m and m.get("bridgeSessionId") else ""


def resume_argv(sid, title=None):
    return start_argv(title) + ["-r", sid]


def start_argv(title=None):
    if REMOTE:
        return [claude_exe(), "--remote-control"] + ([title] if title else [])
    return [claude_exe()] + (["-n", title] if title else [])


# Sessions on the private tmux server.

def sessions():
    """Every managed session; `asleep` means the pane holds the shell, not claude."""
    fmt = "\t".join(["#{session_name}", "#{pane_pid}", "#{@sid}", "#{session_path}", "#{@title}"])  # title last: it may hold anything
    out, table = [], process_table()
    for line in tmux("list-panes", "-a", "-F", fmt).stdout.splitlines():
        name, pid, sid, path, title = line.split("\t", 4)
        m = meta(pid) if is_claude(int(pid), table) else None
        out.append(dict(name=name, pid=int(pid), meta=m, asleep=is_hold(table.get(int(pid), (0, "", ""))[2]),
                        sid=m["sessionId"] if m else sid, title=clean((m or {}).get("name") or title or name),
                        cwd=(m or {}).get("cwd") or path, status=(m or {}).get("status", ""), tty=""))
    return out + native_sessions(out, table)


def process_table():
    """{pid: (ppid, tty, command)} from one ps call, however many sessions there are."""
    out = subprocess.run(["ps", "-axww", "-o", "pid=,ppid=,tty=,command="], capture_output=True, text=True).stdout
    table = {}
    for line in out.splitlines():
        pid, ppid, tty, command = (line.split(None, 3) + [""])[:4]
        table[int(pid)] = (int(ppid), tty, command)
    return table


def started(pid):
    """When a process started, in the form claude keeps as procStart, whatever the locale or time zone."""
    return subprocess.run(["ps", "-o", "lstart=", "-p", str(pid)], capture_output=True, text=True,
                          env={**os.environ, "LC_ALL": "C", "TZ": "UTC"}).stdout.strip()


def same_process(pid, m):
    """A pid is reused after a crash; the start time claude wrote down tells the two apart."""
    return not m.get("procStart") or m["procStart"] == started(pid)


def is_hold(command):
    return "ccstay-hold" in command


def is_claude(pid, table):
    """Claude's session file outlives a crash, and the pid in it may belong to something else by now."""
    command = table[pid][2] if pid in table else ""
    return "claude" in command and not is_hold(command)  # a sleeping session's command line names claude too


def parent_is_shell(pid, table):
    parent = table.get(table.get(pid, (0,))[0], (0, "", ""))[2].split(" ", 1)[0]
    return os.path.basename(parent).lstrip("-") in ("sh", "bash", "zsh", "fish")


def in_iterm(pid, table):
    while pid in table and pid > 1:
        if "iTerm" in table[pid][2]:
            return True
        pid = table[pid][0]
    return False


def native_sessions(managed, table):
    """Sessions running straight in an iTerm tab, awake or held by ccstay. macOS only."""
    if sys.platform != "darwin" or os.environ.get("CCSTAY_NATIVE") == "0":
        return []
    known, out = {s["pid"] for s in managed}, []
    taken, saved = {s["name"] for s in managed}, read_snapshot()
    for f in glob.glob(f"{CLAUDE_DIR}/sessions/*.json"):
        pid = int(os.path.basename(f)[:-5])
        m = meta(pid)
        if m and is_claude(pid, table) and pid not in known and m.get("kind", "interactive") == "interactive" \
                and in_iterm(pid, table) and same_process(pid, m):
            title = clean(m.get("name")) or m["sessionId"][:8]
            name = unique_name(title, taken)
            taken.add(name)
            out.append(dict(name=name, pid=pid, meta=m, asleep=False, sid=m["sessionId"], title=title,
                            cwd=m.get("cwd", ""), status=m.get("status", ""), tty=f"/dev/{table[pid][1]}"))
    for pid, (_, tty, command) in table.items():
        hit = re.search(r"ccstay-hold .*?/screens/([0-9a-f-]+)", command)
        # a tab's tmux client carries the same text when it started a sleeping session
        if hit and "tmux" not in command.split()[0] and pid not in known and in_iterm(pid, table):
            sid, e = hit.group(1), saved.get(hit.group(1), {})
            name = unique_name(e.get("title", sid[:8]), taken)
            taken.add(name)
            out.append(dict(name=name, pid=pid, meta=None, asleep=True, sid=sid, title=e.get("title", name),
                            cwd=e.get("cwd", HOME), status="", tty=f"/dev/{tty}"))
    return out


def osa(script, timeout=45, quiet=False):
    try:
        return subprocess.run(["osascript", "-"], input=script, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        if not quiet:
            die("the terminal did not respond")
        return subprocess.CompletedProcess("osascript", 1, "", "timed out")


def in_tab(s, action):
    """Run AppleScript against the iTerm session `s` of the tab holding this session."""
    return osa(f'''tell application "iTerm"
  repeat with w in windows
    repeat with t in tabs of w
      repeat with s in sessions of t
        if tty of s is "{s["tty"]}" then
          {action}
          return
        end if
      end repeat
    end repeat
  end repeat
end tell''').stdout


def quoted(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def type_line(s, line):
    in_tab(s, f'tell s to write text "{quoted(line)}"')


def shell_line(cwd, argv):
    args = " ".join("\\" * a.startswith("=") + shlex.quote(a) for a in argv)  # zsh reads a leading = as a lookup
    return f" cd {shlex.quote(cwd)} && {args}"  # the space keeps it out of shell history


def server_id():
    """The tmux server's start time, empty when it is not running."""
    return tmux("display-message", "-p", "#{start_time}").stdout.strip()


def find(query, pool, key=lambda s: False):
    hits = [s for s in pool if query in (s["name"], s["sid"]) or key(s)] or \
           [s for s in pool if query in s["name"] or query in s["title"]]
    if len(hits) == 1:
        return hits[0]
    die(f"{query!r} matches {', '.join(s['name'] for s in hits)}" if hits else f"no session matches {query!r}")


def unique_name(base, taken):
    base = re.sub(r"[.:\s]+", "-", base).strip("-") or "session"
    name, n = base, 2
    while name in taken:
        name, n = f"{base}-{n}", n + 1
    return name


def stop(pid, timeout=STOP_SECONDS):
    try:
        os.kill(pid, signal.SIGTERM)
    except ProcessLookupError:
        return True
    deadline = time.time() + timeout
    while time.time() < deadline:
        state = subprocess.run(["ps", "-o", "stat=", "-p", str(pid)], capture_output=True, text=True).stdout
        if not state.strip() or state.startswith("Z"):  # a zombie has already ended
            return True
        time.sleep(0.2)
    return False


def swap(s, argv):
    """End claude and start `argv` in the same pane, so attached tabs stay put."""
    if s["tty"]:
        # the replacement is typed in, so there must be a tab and a shell waiting underneath claude
        if not in_tab(s, "return tty of s").strip() or not parent_is_shell(s["pid"], process_table()):
            log(f"{s['name']}: no shell tab to type into, left alone")
            return False
        if not stop(s["pid"]):
            log(f"{s['name']}: did not exit in time, left alone")
            return False
        type_line(s, shell_line(s["cwd"], argv))
        return True
    target = f"={s['name']}:"
    tmux("set-option", "-w", "-t", target, "remain-on-exit", "on")
    try:
        stop(s["pid"])  # a chance to save; respawn-pane -k ends it if it is still going
        return tmux("respawn-pane", "-k", "-t", target, "-c", s["cwd"], *argv).returncode == 0
    finally:
        tmux("set-option", "-wu", "-t", target, "remain-on-exit")


def screen_file(sid):
    return f"{STATE_DIR}/screens/{sid}.txt"


def hold_argv(sid, title):
    return ["/bin/sh", "-c", HOLD, "ccstay-hold", screen_file(sid), title, *resume_argv(sid, title)]


def put_to_sleep(s):
    os.makedirs(f"{STATE_DIR}/screens", mode=0o700, exist_ok=True)
    if s["tty"]:
        screen = in_tab(s, "return contents of s").rstrip()
    else:
        screen = tmux("capture-pane", "-e", "-p", "-t", f"={s['name']}:").stdout.rstrip()
        tmux("set-option", "-t", f"={s['name']}:", "@sid", s["sid"])
        tmux("set-option", "-t", f"={s['name']}:", "@title", s["title"])
    write_atomic(screen_file(s["sid"]), screen + "\n")
    remember(s, asleep=True)
    ok = swap(s, hold_argv(s["sid"], s["title"]))
    log(f"{s['name']}: {'asleep' if ok else 'sleep failed'}")
    return ok


def remember(s, **fields):
    set_fields(s["sid"], **{**record(s, *current_ids()), **fields})


def keep_ids():
    try:
        with open(KEEP) as f:
            return set(f.read().split())
    except OSError:
        return set()


def idle_seconds(s):
    return time.time() - last_active(s["meta"])


def has_conversation(s):
    """claude -r fails on a session with no messages yet, so it could never wake up."""
    return os.path.exists(transcript(s["cwd"], s["sid"]))


def should_sleep(s, keep):
    return (s["meta"] and not s["tty"] and s["sid"] not in keep and s["status"] not in BUSY and s["status"] != "waiting"
            and has_conversation(s) and idle_seconds(s) >= IDLE_HOURS * 3600)


def wait_for(fn, timeout, step=0.5):
    deadline = time.time() + timeout
    while time.time() < deadline:
        v = fn()
        if v:
            return v
        time.sleep(step)
    return None


# Terminals. Each one only has to open a tab that runs a command.

ITERM_WINDOW = """  set target to missing value
  set fresh to {new}
  try
    set target to current window
    get id of target
  on error  -- nothing has focus while the screen is locked, and creating a window then can hang
    set fresh to false
    set target to missing value
    repeat with w in windows
      if (count of tabs of w) > 0 then
        set target to contents of w
        exit repeat
      end if
    end repeat
  end try
"""

ITERM = f"""tell application "iTerm"
{ITERM_WINDOW}  if target is missing value or fresh then
    create window with default profile command "{{c}}"
  else
    tell target to create tab with default profile command "{{c}}"
  end if
end tell"""

ITERM_SHELL = f"""tell application "iTerm"
{ITERM_WINDOW}  if target is missing value or fresh then
    set target to (create window with default profile)
  else
    tell target to create tab with default profile
  end if
  tell current session of current tab of target
    write text "{{c}}"
    return tty
  end tell
end tell"""

GHOSTTY = """tell application "Ghostty"
  set cfg to new surface configuration
  set command of cfg to "{c}"
  if (count of windows) = 0 or {new} then
    new window with configuration cfg
  else
    new tab in front window with configuration cfg
  end if
end tell"""

