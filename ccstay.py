# macOS grants Automation per launching program and refuses osascript started by a scheduled Python,
# so zsh asks first, as a program whose permission survives Python upgrades, and Python reads the result.
PLIST = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>Label</key><string>{TIMER_ID}</string>
<key>ProgramArguments</key><array><string>/bin/zsh</string><string>-c</string><string>@COMMAND@</string></array>
<key>StandardErrorPath</key><string>@LOG@</string>
<key>StartInterval</key><integer>{TICK_SECONDS}</integer>
<key>ProcessType</key><string>Background</string>
<key>LowPriorityIO</key><true/>
</dict></plist>
"""
UNIT = """[Service]
Type=oneshot
Nice=19
@ENV@ExecStart=@SELF@ tick
"""
TIMER = f"""[Timer]
OnBootSec={TICK_SECONDS}s
OnUnitActiveSec={TICK_SECONDS}s
[Install]
WantedBy=timers.target
"""


def layout_zsh():
    tmux_cmd = shlex.join(tmux_base() + ["list-clients", "-F", "#{client_termname}"])
    ask = {"iTerm": "/usr/bin/pgrep -aqx iTerm2",  # Ghostty only when a session is shown there: it means a prompt
           "Ghostty": f"/usr/bin/pgrep -aqx ghostty && {tmux_cmd} 2>/dev/null | grep -q ghostty"}
    done, tmp = shlex.quote(LAYOUT), shlex.quote(f"{LAYOUT}.tmp")
    steps = "".join(f"{check} && /usr/bin/osascript <<'OSA' >> {tmp}\n{layout_script(app)}\nOSA\n"
                    for app, check in ask.items())
    return f"# Generated by ccstay.\n: > {tmp}\n{steps}mv {tmp} {done}\n"


def cmd_timer(a):
    me, zsh = shlex.quote(self_path()), shlex.quote(LAYOUT_ZSH)
    keep = {k: v for k, v in sorted(os.environ.items())  # a timer sees none of the user's shell setup
            if (k.startswith("CCSTAY_") and k != "CCSTAY_SCHEDULED")
            or k in ("CLAUDE_CONFIG_DIR", "XDG_STATE_HOME", "XDG_CONFIG_HOME")}
    exports = "".join(f"export {k}={shlex.quote(v)}; " for k, v in keep.items())
    plist = PLIST.replace("@COMMAND@", html.escape(f"{exports}/bin/zsh {zsh}; CCSTAY_SCHEDULED=1 {me} tick")) \
        .replace("@LOG@", html.escape(LOG))

    def run(*command):
        try:
            r = subprocess.run(command, capture_output=True, text=True)
        except FileNotFoundError:
            die(f"{command[0]} not found; this system has no user timer ccstay can use")
        if r.returncode:
            die(f"{' '.join(command)}: {r.stderr.strip()}")

    if sys.platform == "darwin":
        path = f"{HOME}/Library/LaunchAgents/{TIMER_ID}.plist"
        target = f"gui/{os.getuid()}"
        subprocess.run(["launchctl", "bootout", f"{target}/{TIMER_ID}"], capture_output=True)
        if a.state == "off":
            if os.path.exists(path):
                os.remove(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            write_atomic(LAYOUT_ZSH, layout_zsh())
            write_atomic(path, plist)
            run("launchctl", "bootstrap", target, path)
    else:
        d = f"{os.path.dirname(CONFIG_DIR)}/systemd/user"
        if a.state == "off":
            if shutil.which("systemctl"):
                subprocess.run(["systemctl", "--user", "disable", "--now", "ccstay.timer"], capture_output=True)
            for f in ("ccstay.service", "ccstay.timer"):
                if os.path.exists(f"{d}/{f}"):
                    os.remove(f"{d}/{f}")
        else:
            os.makedirs(d, exist_ok=True)
            env = "".join(f"Environment={shlex.quote(f'{k}={v}')}\n" for k, v in keep.items())
            write_atomic(f"{d}/ccstay.service", UNIT.replace("@SELF@", me).replace("@ENV@", env))
            write_atomic(f"{d}/ccstay.timer", TIMER)
            run("systemctl", "--user", "enable", "--now", "ccstay.timer")
    print(f"timer {a.state}")


