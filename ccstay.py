    found = moved_transcript(s["sid"])
    if not found:
        die(f"{s['name']} has no conversation to resume yet")
    print(f"{s['name']}: no conversation in {s['cwd'].replace(HOME, '~')}\nfound {found.replace(HOME, '~')}")
