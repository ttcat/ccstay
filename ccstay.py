def cmd_restore(a):
    saved = reconcile(sessions())
    lost = [e for e in saved.values() if e["state"] == "interrupted"]
    missing = [e for e in lost if not os.path.isdir(e["cwd"])]
    pending = sorted((e for e in lost if os.path.isdir(e["cwd"])), key=lambda e: (e.get("window", ""), e.get("tab", 0)))
    for e in pending:
        print(f"{'asleep' if e['asleep'] else 'awake ':7} {e['name']}  {e['cwd'].replace(HOME, '~')}")
    for e in missing:
        print(f"skipped, folder is gone: {e['cwd']}")
    if a.dry_run or not pending:
        print("nothing to restore" if not pending else f"{len(pending)} session(s), dry run")
        return
    term = pick_terminal(a.terminal) if a.tabs else None
    gates = f"{STATE_DIR}/gates"
    os.makedirs(gates, exist_ok=True)
    window, held = None, []
    try:
        for e in pending:  # tabs first, in their old order, each holding claude back
            fresh = bool(term or e.get("native")) and e.get("window") != window
            window = e.get("window")
            gate = None if e["asleep"] else f"{gates}/{e['sid']}"
            if gate:
                open(gate, "w").close()
                held.append((e, gate))
            set_fields(e["sid"], **reopen(e, term, fresh and bool(window), gate))
    finally:  # even after an error, never leave a tab held
        # The phone lists sessions by last activity and a start counts as one: start the most recent last.
        for e, gate in sorted(held, key=lambda h: last_worked(h[0])):
            os.remove(gate)
            wait_for(lambda: any(s["sid"] == e["sid"] and s["meta"] for s in sessions()), 5, step=0.1)  # one at a time
    print(f"restored {len(pending)} session(s)")


def cmd_hook(a):
    """Called by Claude Code at session start and end. Must return fast and never fail the session."""
    try:
        event = json.load(sys.stdin)
        with open(EVENTS, "a", encoding="utf-8") as f:
            f.write(json.dumps(dict(sid=event.get("session_id", ""), reason=event.get("reason"), time=time.time())) + "\n")
        subprocess.Popen([sys.executable, os.path.realpath(__file__), "_sync"], stdin=subprocess.DEVNULL,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)
    except Exception:  # noqa: S110 - a broken hook must never reach Claude Code
        return


def cmd_sync(a):
    time.sleep(2)  # let Claude Code register or remove the session first
    reconcile(sessions())
    page_sync()


def is_our_hook(hook):
    command = hook.get("command", "")
    return "ccstay" in command and command.endswith(" hook")


def cmd_hooks(a):
    """Optional: record session starts and exits at once instead of at the next check."""
    path = os.path.realpath(f"{CLAUDE_DIR}/settings.json")  # it may be a symlink into someone's dotfiles
    try:
        with open(path) as f:
            text = f.read()
    except FileNotFoundError:
        if a.state == "off":
            print("hooks off")
            return
        text = "{}"
    settings = json.loads(text)
    hooks = settings.setdefault("hooks", {})
    for name in ("SessionStart", "SessionEnd"):
        kept = [h for h in hooks.get(name, []) if not any(is_our_hook(c) for c in h.get("hooks", []))]
        if a.state == "on":
            command = f"{shlex.quote(self_path())} hook"
            kept.append({"hooks": [{"type": "command", "command": command, "timeout": 5}]})
        if kept:
            hooks[name] = kept
        else:
            hooks.pop(name, None)
    if not hooks:
        del settings["hooks"]
    new = json.dumps(settings, ensure_ascii=False, indent=2) + "\n"
    if new != text and not os.path.exists(f"{path}.ccstay-backup") and os.path.exists(path):
        shutil.copy2(path, f"{path}.ccstay-backup")
    if new != text:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        write_atomic(path, new, keep_mode=True)
    print(f"hooks {a.state}")


