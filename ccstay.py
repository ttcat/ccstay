PAGE_SECONDS = float(os.environ.get("CCSTAY_PAGE_SECONDS", "120"))  # at most one publish per this many seconds; a change in between goes out on a later tick
PAGE_HELPER = """# ccstay page helper
<!-- Generated by ccstay. -->
This session only republishes the ccstay folders page. Every message `publish` means: call the Artifact tool once with
action publish, file_path {file}, and url read from {url}. If that file is missing or empty, publish without url and
write the new link into it. If a publish is refused because the artifact was not read in this conversation, read it
once, then publish again. Reply with one word: ok, or the error. Do nothing else.
"""


def page_tmux(*args):
    return subprocess.run([*tmux_base()[:1], "-L", PAGE_SOCKET, *args], capture_output=True, text=True, env=clean_env())


def page_helper():
    """True when the helper is running and can take a message; starts it otherwise (ready by the next tick)."""
    if page_tmux("has-session", "-t", "=page").returncode == 0:
        if "Yes, I trust this folder" in page_tmux("capture-pane", "-p", "-t", "=page:").stdout:
            page_tmux("send-keys", "-t", "=page:", "Down")  # the folder is ours, made by page_on
            time.sleep(0.5)
            page_tmux("send-keys", "-t", "=page:", "Enter")
            return False
        return True
    os.makedirs(f"{PAGE_DIR}/.claude", exist_ok=True)
    write_atomic(f"{PAGE_DIR}/CLAUDE.md", PAGE_HELPER.format(file=PAGE_FILE, url=PAGE_URL))
    # no Remote Control, so the helper stays out of the phone's session list
    write_atomic(f"{PAGE_DIR}/.claude/settings.json", json.dumps({"permissions": {"allow": ["Artifact"]}, "remoteControlAtStartup": False}) + "\n")
    page_tmux("new-session", "-d", "-s", "page", "-c", PAGE_DIR, claude_exe(), "--model", "haiku")
    log("page helper started")
    return False


def page_sync(now=None):
    """Called every tick and after each session start or exit: republish the page when what it shows has changed."""
    try:
        with open(PAGE_AUTO) as f:
            sent = f.read().split()
    except OSError:
        return  # auto is off
    now = now or time.time()
    rows, closed = folder_rows(now), closed_rows(now)
    sig = hashlib.sha1(json.dumps([sorted((r["key"], r["state"], r["title"]) for r in rows),
                                   [e["sid"] for e in closed]], ensure_ascii=False).encode()).hexdigest()
    last_sig, last_time = (sent + ["", "0"])[:2]
    if sig == last_sig or now - float(last_time) < PAGE_SECONDS or not page_helper():
        return
    found, _ = themes()
    write_atomic(PAGE_FILE, folders_page(rows, closed, now, found.values(), page_theme(found)))
    page_tmux("send-keys", "-t", "=page:", "-l", "publish")
    page_tmux("send-keys", "-t", "=page:", "Enter")
    write_atomic(PAGE_AUTO, f"{sig} {now}\n")


def cmd_page(a):
    if a.state == "on":
        if not os.path.exists(PAGE_AUTO):
            write_atomic(PAGE_AUTO, "\n")
        page_helper()
        print("page auto on: the page republishes itself within a few minutes of any change")
    else:
        if os.path.exists(PAGE_AUTO):
            os.remove(PAGE_AUTO)
        page_tmux("kill-server")
        print("page auto off")


def cmd_themes(a):
    """Themes the page can show, shipped and personal."""
    found, problems = themes()
    for p in problems:
        print(p, file=sys.stderr)
    if not found:
        print("no themes found; looked in " + ", ".join(d.replace(HOME, "~") for d in theme_dirs()))
        return
    w = max(len(n) for n in found)
    for t in found.values():
        mark = "*" if t["id"] == DEFAULT_THEME else " "
        print(f"{mark} {t['id']:<{w}}  {t['name']['en']} / {t['name']['zh']}  ({t['author']})  {t['path'].replace(HOME, '~')}")
    print(f"\n* default. Pick another with ccstay folders --theme <name>; personal themes go in {CONFIG_DIR.replace(HOME, '~')}/themes/<name>/")


# macOS grants Automation per launching program and refuses osascript started by a scheduled Python,
# so zsh asks first, as a program whose permission survives Python upgrades, and Python reads the result.
PLIST = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>Label</key><string>{TIMER_ID}</string>
<key>ProgramArguments</key><array><string>/bin/zsh</string><string>-c</string><string>@COMMAND@</string></array>
<key>StandardErrorPath</key><string>@LOG@</string>
<key>StartInterval</key><integer>{TICK_SECONDS}</integer>
<key>ProcessType</key><string>Background</string>
<key>LowPriorityIO</key><true/>
</dict></plist>
"""
# At login, a while after it so the network and the terminal are up. The trailing `:` keeps zsh from
# handing itself over to Python, so the Automation prompt is zsh's, which the tick has already granted.
RESTORE_PLIST = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>Label</key><string>{RESTORE_ID}</string>
<key>ProgramArguments</key><array><string>/bin/zsh</string><string>-c</string><string>@COMMAND@</string></array>
<key>StandardOutPath</key><string>@LOG@</string>
<key>StandardErrorPath</key><string>@LOG@</string>
<key>RunAtLoad</key><true/>
</dict></plist>
"""
UNIT = """[Service]
Type=oneshot
Nice=19
@ENV@ExecStart=@SELF@ tick
"""
TIMER = f"""[Timer]
OnBootSec={TICK_SECONDS}s
OnUnitActiveSec={TICK_SECONDS}s
[Install]
WantedBy=timers.target
"""


def layout_zsh():
    tmux_cmd = shlex.join(tmux_base() + ["list-clients", "-F", "#{client_termname}"])
    ask = {"iTerm": "/usr/bin/pgrep -aqx iTerm2",  # Ghostty only when a session is shown there: it means a prompt
           "Ghostty": f"/usr/bin/pgrep -aqx ghostty && {tmux_cmd} 2>/dev/null | grep -q ghostty"}
    done, tmp = shlex.quote(LAYOUT), shlex.quote(f"{LAYOUT}.tmp")
    steps = "".join(f"{check} && /usr/bin/osascript <<'OSA' >> {tmp}\n{layout_script(app)}\nOSA\n"
                    for app, check in ask.items())
    return f"# Generated by ccstay.\n: > {tmp}\n{steps}mv {tmp} {done}\n"


def kept_env():
    """A timer sees none of the user's shell setup: the settings ccstay needs to find its files."""
    return {k: v for k, v in sorted(os.environ.items())
            if (k.startswith("CCSTAY_") and k != "CCSTAY_SCHEDULED")
            or k in ("CLAUDE_CONFIG_DIR", "XDG_STATE_HOME", "XDG_CONFIG_HOME")}


def cmd_autorestore(a):
    """Run `restore --tabs` at each login. Only written now, so it first runs at the next login."""
    if sys.platform != "darwin":
        die("restoring at login is macOS only for now; after a reboot, run ccstay restore --tabs")
    path = f"{HOME}/Library/LaunchAgents/{RESTORE_ID}.plist"
    subprocess.run(["launchctl", "bootout", f"gui/{os.getuid()}/{RESTORE_ID}"], capture_output=True)
    if a.state == "off":
        if os.path.exists(path):
            os.remove(path)
    else:
        exports = "".join(f"export {k}={shlex.quote(v)}; " for k, v in kept_env().items())
        command = f"{exports}sleep 20; {shlex.quote(self_path())} restore --tabs; :"
        os.makedirs(os.path.dirname(path), exist_ok=True)
        write_atomic(path, RESTORE_PLIST.replace("@COMMAND@", html.escape(command)).replace("@LOG@", html.escape(LOG)))
    print(f"restore at login {a.state}")


def cmd_timer(a):
    me, zsh = shlex.quote(self_path()), shlex.quote(LAYOUT_ZSH)
    keep = kept_env()
    exports = "".join(f"export {k}={shlex.quote(v)}; " for k, v in keep.items())
    plist = PLIST.replace("@COMMAND@", html.escape(f"{exports}/bin/zsh {zsh}; CCSTAY_SCHEDULED=1 {me} tick")) \
        .replace("@LOG@", html.escape(LOG))

    def run(*command):
        try:
            r = subprocess.run(command, capture_output=True, text=True)
        except FileNotFoundError:
            die(f"{command[0]} not found; this system has no user timer ccstay can use")
        if r.returncode:
            die(f"{' '.join(command)}: {r.stderr.strip()}")

    if sys.platform == "darwin":
        path = f"{HOME}/Library/LaunchAgents/{TIMER_ID}.plist"
        target = f"gui/{os.getuid()}"
        subprocess.run(["launchctl", "bootout", f"{target}/{TIMER_ID}"], capture_output=True)
        if a.state == "off":
            if os.path.exists(path):
                os.remove(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            write_atomic(LAYOUT_ZSH, layout_zsh())
            write_atomic(path, plist)
            run("launchctl", "bootstrap", target, path)
    else:
        d = f"{os.path.dirname(CONFIG_DIR)}/systemd/user"
        if a.state == "off":
            if shutil.which("systemctl"):
                subprocess.run(["systemctl", "--user", "disable", "--now", "ccstay.timer"], capture_output=True)
            for f in ("ccstay.service", "ccstay.timer"):
                if os.path.exists(f"{d}/{f}"):
                    os.remove(f"{d}/{f}")
        else:
            os.makedirs(d, exist_ok=True)
            env = "".join(f"Environment={shlex.quote(f'{k}={v}')}\n" for k, v in keep.items())
            write_atomic(f"{d}/ccstay.service", UNIT.replace("@SELF@", me).replace("@ENV@", env))
            write_atomic(f"{d}/ccstay.timer", TIMER)
            run("systemctl", "--user", "enable", "--now", "ccstay.timer")
    print(f"timer {a.state}")


