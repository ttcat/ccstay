def saved_choice(path):
    try:
        with open(path) as f:
            return f.read().strip()
    except OSError:
        return ""


def ask_terminal():
    """With both terminals installed, ask once which one new sessions should open in."""
    if not all(os.path.exists(f"/Applications/{app}.app") for app in ("iTerm", "Ghostty")):
        return
    answer = input("Open sessions in iTerm, Ghostty or Terminal? [i/g/t, Enter follows the terminal you are in] ").strip().lower()[:1]
    choice = {"i": "iterm", "g": "ghostty", "t": "terminal"}.get(answer)
    if choice:
        write_atomic(TERMINAL_FILE, choice + "\n")
        print(f"sessions will open in {choice}")


def pick_terminal(wanted):
    name = wanted or os.environ.get("CCSTAY_TERMINAL", "") or saved_choice(TERMINAL_FILE)
    if name:
        return None if name == "none" else name
    found = {"iterm.app": "iterm", "ghostty": "ghostty", "apple_terminal": "terminal"}.get(os.environ.get("TERM_PROGRAM", "").lower())
    if found:
        return found
    if sys.platform == "darwin":
        if subprocess.run(["pgrep", "-aqx", "iTerm2"]).returncode == 0:
            return "iterm"
        if subprocess.run(["pgrep", "-aqx", "ghostty"]).returncode == 0:
            return "ghostty"
        if subprocess.run(["pgrep", "-aqx", "Terminal"]).returncode == 0:
            return "terminal"
    return None


def open_tab(term, argv, new_window=False):
    if term not in TERMINALS:
        die(f"unknown terminal {term!r}, use one of: {', '.join(TERMINALS)}, none")
    if term == "terminal":  # typed into the user's shell, and zsh expands the =name tmux needs
        argv = ["/bin/sh", "-c", "exec " + shlex.join(argv)]
    cmd = quoted(shlex.join(argv))
    r = osa(TERMINALS[term].format(c=cmd, new=str(new_window).lower()), quiet=True)  # a first launch or permission prompt takes a while
    if r.stderr == "timed out":
        die(f"{term} did not respond, is the screen locked? Use --terminal none to run detached")
    if r.returncode:
        die(f"could not open a {term} tab: {r.stderr.strip()}")


def start_native(cwd, argv, new_window=False):
    """Start in an iTerm tab's own shell, with no tmux. Returns the tab's tty."""
    r = osa(ITERM_SHELL.format(c=quoted(shell_line(cwd, argv)), new=str(new_window).lower()))
    if r.returncode or not r.stdout.startswith("/dev/"):
        die(f"could not open an iterm tab: {r.stderr.strip()}")
    return r.stdout.strip()


def start(name, cwd, argv, term, new_window=False):
    """Start a session in a new tab, or detached when there is no terminal to use."""
    os.makedirs(STATE_DIR, exist_ok=True)
    write_atomic(TMUX_CONF, CONF.replace("@CONFIG@", quoted(CONFIG_DIR)))
    if term:
        try:
            open_tab(term, tmux_base() + ["new-session", "-A", "-s", name, "-c", cwd, *argv], new_window)
            if wait_for(lambda: tmux("has-session", "-t", f"={name}").returncode == 0, 10):
                return term
        except SystemExit:
            pass  # claude needs no window: start it anyway, the phone can reach it
        print(f"note: {term} did not open a tab, starting detached; show it later with: ccstay open {shlex.quote(name)}")
    if tmux("new-session", "-d", "-s", name, "-c", cwd, *argv).returncode:
        die(f"could not start session {name}")
    return None


