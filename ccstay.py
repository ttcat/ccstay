def main():
    if len(sys.argv) == 1:
        print(GETTING_STARTED)
        return
    a = parser().parse_args()
    try:
        os.makedirs(STATE_DIR, mode=0o700, exist_ok=True)
        os.chmod(STATE_DIR, 0o700)  # screens hold whatever was on the terminal
    except OSError as e:
        if a.cmd == "hook":
            return
        die(f"cannot use {STATE_DIR}: {e}")
    try:
        a.fn(a)
    except Exception:
        if a.cmd in ("hook", "tick"):
            raise
        traceback.print_exc()
        die(f"unexpected error\n{FIX_IT}")


if __name__ == "__main__":
    main()
