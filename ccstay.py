def fit(s, n):
    """Pad or cut to n display cells, counting CJK characters as two."""
    out, used = "", 0
    for c in " ".join(s.split()):
        w = 2 if unicodedata.east_asian_width(c) in "WF" else 1
        if used + w > n - 1:
            return out + "…" + " " * max(0, n - used - 1)
        out, used = out + c, used + w
    return out + " " * (n - used)


def json_tail(path, key, blob=None):
    """Latest value of a top-level string field, without parsing the whole transcript."""
    if blob is None:
        with open(path, "rb") as f:
            f.seek(max(0, os.path.getsize(path) - 512 * 1024))
            blob = f.read()
    hits = re.findall(rb'"%s":"((?:[^"\\]|\\.)*)"' % key, blob)
    if not hits:
        return ""
    try:
        return json.loads(b'"' + hits[-1] + b'"')
    except ValueError:
        return ""


